async page => {
  const origin = await page.evaluate(() => location.origin);
  const folder = '/home/lsl/macbook/pai-studio-fin/projects/stockev.qtask_list/docs/test/20261017-17-WORKTREE/browser-3';
  const checks = [];
  const failures = [];
  const assert = (value, message) => { if (!value) throw new Error(message); };
  page.on('pageerror', error => failures.push(error.message));
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
  for (const name of ['review/slash', '中文/队列', 'review%2Fname']) {
    await page.goto(`${origin}/queues/${encodeURIComponent(name)}?state=ready`);
    await page.locator('.topbar select').selectOption('0');
    await page.locator('tbody tr').first().waitFor();
    assert(await page.locator('h1').innerText() === name, `队列名被二次解码：${name}`);
    await page.locator('tbody tr').first().click();
    const drawer = page.getByRole('dialog', { name: '任务详情', exact: true });
    await drawer.getByRole('button', { name: '加载完整 payload', exact: true }).click();
    await drawer.locator('pre.code').filter({ hasText: name }).waitFor();
    await page.keyboard.press('Escape');
    await drawer.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '操作 ▾', exact: true }).click();
    await page.getByRole('button', { name: '诊断', exact: true }).click();
    const diagnose = page.getByRole('dialog', { name: `诊断 · ${name}`, exact: true });
    await diagnose.waitFor();
    await page.keyboard.press('Shift+Tab');
    assert(await diagnose.evaluate(element => element.contains(document.activeElement)), '诊断焦点逃逸');
    await page.keyboard.press('Escape');
    await diagnose.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '操作 ▾', exact: true }).click();
    await page.getByRole('button', { name: '投递任务…', exact: true }).click();
    const push = page.getByRole('dialog', { name: '投递任务', exact: true });
    await push.waitFor();
    await push.getByLabel(/handler action/).fill('review_action');
    await push.locator('textarea').fill('[');
    await push.getByRole('button', { name: '投递', exact: true }).click();
    await push.getByText('⚠ payload 不是合法 JSON', { exact: true }).waitFor();
    await push.locator('textarea').fill(JSON.stringify({ source: '浏览器回归', queue: name }));
    await page.keyboard.press('Shift+Tab');
    assert(await push.evaluate(element => element.contains(document.activeElement)), '投递弹窗焦点逃逸');
    const posted = page.waitForResponse(response => response.url().includes('/api/queues/tasks?') && response.request().method() === 'POST');
    await push.getByRole('button', { name: '投递', exact: true }).click();
    const result = await (await posted).json();
    assert(result.accepted && result.queue === name, JSON.stringify(result));
    await push.waitFor({ state: 'hidden' });
    await page.locator(`tbody td[title="${result.task_id}"]`).waitFor();
    await page.locator(`tbody td[title="${result.task_id}"]`).click();
    await drawer.getByRole('button', { name: '删除', exact: true }).click();
    const removeTask = page.getByRole('dialog', { name: '删除任务', exact: true });
    const removed = page.waitForResponse(response => response.url().includes('/api/tasks/detail?') && response.request().method() === 'DELETE');
    await removeTask.getByRole('button', { name: '删除', exact: true }).click();
    assert((await removed).status() === 200, '删除特殊名称队列的任务失败');
    await drawer.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '⚠ 危险操作 ▾', exact: true }).click();
    await page.getByRole('button', { name: '清空队列…', exact: true }).click();
    const clear = page.getByRole('dialog', { name: `清空队列 ${name}`, exact: true });
    await clear.getByRole('textbox').fill('wrong');
    assert(!await clear.getByRole('button', { name: '清空', exact: true }).isEnabled(), '错误名称可清空');
    await clear.getByRole('textbox').fill(name);
    const cleared = page.waitForResponse(response => response.url().includes('/api/queues/clear?') && response.request().method() === 'POST');
    await clear.getByRole('button', { name: '清空', exact: true }).click();
    assert((await cleared).status() === 200, '清空失败');
    await clear.waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 0);
    if (name === '中文/队列') await page.screenshot({ path: `${folder}/unicode-queue-clear.png` });
    await page.getByRole('button', { name: '⚠ 危险操作 ▾', exact: true }).click();
    await page.getByRole('button', { name: '删除队列…', exact: true }).click();
    const removeQueue = page.getByRole('dialog', { name: `删除队列 ${name}`, exact: true });
    await removeQueue.getByRole('textbox').fill(name);
    const deleted = page.waitForResponse(response => response.url().includes('/api/queues/detail?') && response.request().method() === 'DELETE');
    await removeQueue.getByRole('button', { name: '删除', exact: true }).click();
    assert((await deleted).status() === 200, '删除队列失败');
    await page.waitForURL(`${origin}/queues`);
    const queues = await page.evaluate(async () => await (await fetch('/api/queues')).json());
    assert(!queues.some(queue => queue.name === name), '删除后仍被发现');
    checks.push({ name, result: '读取、payload、诊断、投递校验、投递、删任务、清空、删队列均通过' });
  }
  assert(failures.length === 0, JSON.stringify(failures));
  return { passed: checks.length, checks, failures };
}
